"""Build Ailsa Image Tools from the two tool sources.

    python3 build.py                  -> index.html (standalone page, open it directly or serve it)
    python3 build.py --artifact OUT   -> also writes the body-only version used for the claude.ai artifact

Each tool in src/ is a self-contained page. The build namespaces their element ids (t-, o-) and CSS,
then places them as two tabbed views in one page.
"""
import re, sys, os
HERE=os.path.dirname(os.path.abspath(__file__))
def parts(path):
    s=open(path).read()
    css=s[s.index('<style>')+7:s.index('</style>')]
    a=s.index('<script>\n(() =>')
    markup=s[s.index('</style>')+8:a]
    js=s[a+8:s.index('</script>',a)]
    return css,markup,js

def scope_css(css,root,pfx):
    css=re.sub(r'/\*.*?\*/','',css,flags=re.S)
    # drop everything up to and including the first plain "body{" rule (tokens, html/body)
    m=re.search(r'\nbody\{[^}]*\}',css); css=css[m.end():]
    def sel_fix(sel):
        sel=re.sub(r'#([A-Za-z][\w-]*)',lambda m:'#'+pfx+m.group(1),sel.strip())
        return root+' '+sel
    def walk(t):
        out='';i=0
        while True:
            j=t.find('{',i)
            if j<0: break
            pre=t[i:j].strip()
            if pre.startswith('@'):
                d=1;k=j+1
                while d:
                    if t[k]=='{':d+=1
                    elif t[k]=='}':d-=1
                    k+=1
                out+=pre+'{'+walk(t[j+1:k-1])+'}\n';i=k
            else:
                k=t.index('}',j)
                out+=','.join(sel_fix(x) for x in pre.split(','))+t[j:k+1]+'\n';i=k+1
        return out
    return walk(css)

def prefix_markup(m,pfx):
    return re.sub(r'(?<=\s)(id|for)="(?!\$)',lambda x:f'{x.group(1)}="{pfx}',m).replace('(?<=','')

def prefix_ids(m,pfx):
    return re.sub(r'(?<=\s)(id|for)="',lambda x:f'{x.group(1)}="{pfx}',m)

def fix_js(js,rootid,pfx):
    js=prefix_ids(js,pfx)  # ids inside template strings
    js=js.replace('el.id','K(el)').replace('document.querySelectorAll','ROOT.querySelectorAll')
    js=js.replace("const $ = id => document.getElementById(id);",
      f"const ROOT=document.getElementById('{rootid}'), P='{pfx}';\n  const $ = id => document.getElementById(id.startsWith(P)?id:P+id);\n  const K = el => el.id.slice(P.length);",1)
    return js

